import { describe, it, expect } from "vitest";
import { parseStoreOfficialCsv } from "@/hooks/useSalonBoardData";

/**
 * 店舗詳細の「総売上」カードの内訳（技術 + 店販 + オプション − 割引）の検算。
 *
 * カードの見出しに出しているのは store_official の「純売上」。内訳を技術と店販だけで
 * 出していたので、足しても見出しに届かなかった（監査指摘）。オプションと割引を足して
 * 算式が閉じることを、実スプシ 2026-08 の値でそのまま確かめる。
 *
 * 列: 店舗,年月,純売上,技術,店販,オプション,総売上,割引,客単価,総客数,新規,再来
 * 割引はスプシ上は負値。parseStoreOfficialCsv は表示に合わせて正の大きさへ寄せる。
 */

// 実スプシ store_official の 2026-08 行（7院すべて）。取得したCSVの行をそのまま貼っている
// （ダブルクォート・「広島楽々園院」等の店舗表記・割引の負値も実物のまま）
const CSV_2026_08 = [
  `"店舗","年月","純売上","技術","店販","オプション","総売上","割引","客単価","総客数","新規","再来"`,
  `"堀江院","2026-08","1850950","1816100","38150","12100","1866350","-15400","14461","128","32","96"`,
  `"広島楽々園院","2026-08","2399660","2396750","68100","31020","2495870","-96210","13871","173","29","144"`,
  `"福岡姪浜院","2026-08","3321700","3336300","47000","46200","3429500","-107800","14256","233","48","185"`,
  `"堀江院 2nd","2026-08","1822430","1764500","52450","20350","1837300","-14870","14019","130","32","98"`,
  `"福島院","2026-08","3370700","3324600","40600","35200","3400400","-29700","13702","246","66","180"`,
  `"高槻院","2026-08","1899050","1808200","84250","13200","1905650","-6600","14279","133","20","113"`,
  `"土橋院","2026-08","2349390","2321100","96930","18810","2436840","-87450","12909","182","47","135"`,
].join("\n");

describe("総売上カードの内訳（オプション・割引を含む）", () => {
  const rows = parseStoreOfficialCsv(CSV_2026_08);

  it("7院ぶん読めている", () => {
    expect(rows).toHaveLength(7);
  });

  it("オプションと割引を読んでいる（割引は正の大きさ）", () => {
    const horie = rows.find((r) => r.storeName === "堀江院")!;
    expect(horie.optionSales).toBe(12100);
    expect(horie.discount).toBe(15400);
  });

  it("技術 + 店販 + オプション − 割引 が見出しの純売上に一致する（全7院）", () => {
    for (const r of rows) {
      const sum = r.techSales + r.retailSales + (r.optionSales ?? 0) - (r.discount ?? 0);
      expect({ store: r.storeName, sum }).toEqual({ store: r.storeName, sum: r.totalSales });
    }
  });

  it("技術 + 店販 だけでは見出しに届かない（＝内訳2項目では算式が閉じない）", () => {
    for (const r of rows) {
      expect(r.techSales + r.retailSales).not.toBe(r.totalSales);
    }
  });

  it("オプション・割引の列が無い（短い）行は取り込まない", () => {
    const short = [`"店舗","年月","純売上"`, `"堀江院","2026-08","1850950"`].join("\n");
    expect(parseStoreOfficialCsv(short)).toHaveLength(0);
  });
});
